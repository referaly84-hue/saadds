export function getPresetCommentary(payload: DrawCommentaryPayload): { commentator: string; guest: string; dramaLevel: 'normal' | 'high' | 'derby' } {
  const { team, assignedGroup, rivalsInSlot = [], tournament, targetSlot } = payload;
  const teamNameLower = team.name.toLowerCase();

  // Проверка дерби с соперниками в слоте
  for (const rival of rivalsInSlot) {
    const rivalLower = rival.name.toLowerCase();
    for (const [key, text] of Object.entries(DERBY_NARRATIVES)) {
      const [t1, t2] = key.split('-');
      if (
        (teamNameLower.includes(t1) && rivalLower.includes(t2)) ||
        (teamNameLower.includes(t2) && rivalLower.includes(t1))
      ) {
        return {
          commentator: `ВОТ ЭТО ДА! ${text} ${team.name} попадает к ${rival.name}! Весь зал в Останкино затаил дыхание!`,
          guest: `«Это невероятная удача для зрителей! Такие матчи украшают турнир, трибуны будут переполнены!»`,
          dramaLevel: 'derby'
        };
      }
    }
  }

  // Специфический флейвор команды
  let flavor = '';
  for (const [key, lines] of Object.entries(TEAM_FLAVORS)) {
    if (teamNameLower.includes(key)) {
      flavor = lines[Math.floor(Math.random() * lines.length)];
      break;
    }
  }

  if (tournament === 'cup_rpl') {
    const isTopSeed = team.pot === 1;
    if (isTopSeed) {
      return {
        commentator: `Из первой корзины шар открыт — это ${team.name}! ${flavor || 'Один из главных фаворитов турнира!'}. Он возглавляет ${assignedGroup || targetSlot}!`,
        guest: `«Отличный старт группы. Для этой команды цель одна — только финал в Лужниках.»`,
        dramaLevel: 'high'
      };
    }
    if (team.pot === 4) {
      return {
        commentator: `И замыкает формирование квартета ${team.name}! ${flavor || 'Неуступчивый клуб, готовый отобрать очки у любого гранда!'}. Квартет ${assignedGroup || ''} полностью сформирован!`,
        guest: `«Легких прогулок здесь ни для кого не будет. Кубок России всегда славился сенсациями!»`,
        dramaLevel: 'normal'
      };
    }
    return {
      commentator: `Шар открыт! В слот ${targetSlot} отправляется ${team.name}! ${flavor}`,
      guest: `«Интрига нарастает. В этой группе борьба за первые два места будет идти до 90-й минуты последнего тура!»`,
      dramaLevel: 'normal'
    };
  }

  if (tournament === 'cup_regions') {
    const isMedia = team.comp.startsWith('media');
    if (isMedia) {
      return {
        commentator: `Медиафутбольный представитель на арене — это ${team.name}! ${flavor || 'Клуб с сумасшедшей поддержкой болельщиков!'} Они вступают в 1-й раунд!`,
        guest: `«Медийные команды доказали свой уровень в Кубке России. Недооценивать их — верная путевка на вылет!»`,
        dramaLevel: 'high'
      };
    }
    return {
      commentator: `Профессиональный клуб Второй лиги — ${team.name}! Серьёзное испытание и проверка на прочность для любого соперника!`,
      guest: `«Для ребят из регионов это главный матч года, они будут биться за каждый метр поля!»`,
      dramaLevel: 'normal'
    };
  }

  // Кубок Медиалиги
  return {
    commentator: `Очередной медийный гигант в сетке — ${team.name}! ${flavor || 'Один из самых ярких коллективов лиги!'}`,
    guest: `«В Медиалиге каждый матч — это контент и невероятная страсть. Ждём огненных хайлайтов!»`,
    dramaLevel: 'high'
  };
}

export function buildOfficialRplPots(rplTeams: any[]): DrawPots {
  // Канонический посев клубов РПЛ по корзинам (по силе / занятым местам / престижу)
  const priority = [
    // Корзина 1: Топ-4
    'зенит', 'краснодар', 'динамо', 'локомотив',
    // Корзина 2
    'спартак', 'цска', 'ростов', 'рубин',
    // Корзина 3
    'крылья советов', 'ахмат', 'пари нн', 'факел',
    // Корзина 4
    'оренбург', 'химки', 'динамо махачкала', 'акрон'
  ];

  const matchedTeams = [...rplTeams];
  const sorted: any[] = [];

  for (const p of priority) {
    const idx = matchedTeams.findIndex(t => t.name.toLowerCase().includes(p));
    if (idx !== -1) {
      sorted.push(matchedTeams.splice(idx, 1)[0]);
    }
  }
  // Добавляем оставшихся, если есть
  sorted.push(...matchedTeams);

  const pot1 = sorted.slice(0, 4).map(t => ({ ...t, pot: 1 }));
  const pot2 = sorted.slice(4, 8).map(t => ({ ...t, pot: 2 }));
  const pot3 = sorted.slice(8, 12).map(t => ({ ...t, pot: 3 }));
  const pot4 = sorted.slice(12, 16).map(t => ({ ...t, pot: 4 }));

  return { pot1, pot2, pot3, pot4 };
}
