/**
 * Структура клубов: основная команда + дубли и молодёжные команды — это ОДИН клуб.
 * Любая команда семьи может заявить на конкретный матч игрока из заявки любой другой
 * команды этой же семьи (разовая «аренда на 1 игру», без трансфера и без смены заявки).
 *
 * Ключ — название основной команды, значение — названия её дублей/молодёжки (как в db.teams[].name).
 * Названия похожих, но НЕ связанных клубов («Зенит Пенза», «Рубин Ялта», «Спартак Кострома»,
 * «Спартак-Нальчик», «Спартак Тамбов», «Спартак Владикавказ», «Динамо Брянск» и т.д.) сюда не попадают.
 * Чтобы связать ещё одну команду — достаточно дописать её имя в нужный список.
 */
export const CLUB_FAMILIES: Record<string, string[]> = {
  'Зенит': ['Зенит-2'],
  'Спартак': ['Спартак-2'],
  'Балтика': ['Балтика-2', 'Балтика-БФУ'],
  'Родина': ['Родина-2', 'Родина-3', 'Родина-М'],
  'Ростов': ['Ростов-2'],
  'Рубин': ['Рубин-2'],
  'Крылья Советов': ['Крылья Советов-2'],
  'Оренбург': ['Оренбург-2'],
  'Акрон': ['Акрон-2'],
  'Динамо Махачкала': ['Динамо-2 Махачкала'],
  'Арсенал Тула': ['Арсенал-2'],
  'Ротор': ['Ротор-2'],
  'Урал': ['Урал-2'],
  'Челябинск': ['Челябинск-2'],
  'Енисей': ['Енисей-2'],
  'СКА-Хабаровск': ['СКА-Хабаровск-2']
};

/** Все названия семьи клуба (основа первой), в которую входит команда с таким именем. Если команда не входит ни в одну семью — [name]. */
export function familyNamesOf(name: string): string[] {
  for (const [parent, kids] of Object.entries(CLUB_FAMILIES)) {
    if (parent === name || kids.includes(name)) return [parent, ...kids];
  }
  return [name];
}
